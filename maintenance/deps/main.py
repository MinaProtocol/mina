#!/usr/bin/env python3
"""Dependency gate and advisor for the OCaml tree.

    python3 maintenance/deps/main.py check     # CI gate, fails on regression
    python3 maintenance/deps/main.py advise    # human report: what to delete
    python3 maintenance/deps/main.py baseline  # re-pin baseline.json

Runs without dune, without a switch and without any opam package: it reads
`dune` files directly. See maintenance/README.md for what that costs us.

This module is the imperative shell: argument parsing, file I/O, printing and
exit codes live here, and nothing below it imports them.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from enum import Enum, IntEnum, StrEnum
from pathlib import Path
from typing import Any, NoReturn, assert_never

import analysis
from analysis import Budget, ImpactIndex, LayeringRule, Metric, UnreferencedDep
from graph import DuneGraph, Edge, NodeId, SourceIndex, load_graph
from report import (
    BASELINE_HINT,
    BudgetMoved,
    Failure,
    LayeringBroken,
    MissingEntrypoint,
    NewEntrypoint,
    OpamPackageAdded,
    OpamPackageRemoved,
    UnusedHeavyDep,
    render_failure,
)

HERE = Path(__file__).resolve().parent
BASELINE_PATH = HERE / "baseline.json"
RULES_PATH = HERE / "rules.json"

BASELINE_COMMENT = (
    "Generated by `make deps-baseline`; do not hand-edit.",
    "entrypoints: transitive internal libraries and opam packages per executable.",
    "unreferenced: declared deps with no module reference AND real closure weight.",
    "Numbers may only be changed together with the dune change that causes them.",
)

ADVICE_TOP_ENTRYPOINTS = 20
ADVICE_TOP_STANZAS = 10
ADVICE_SAMPLE_DEPS = 5
ADVICE_SAMPLE_SYMBOLS = 6


class ErrorCode(StrEnum):
    ROOT_NOT_A_DIRECTORY = "ROOT_NOT_A_DIRECTORY"
    BASELINE_MISSING = "BASELINE_MISSING"
    MALFORMED_JSON = "MALFORMED_JSON"


class DepsError(Exception):
    """A failure the CLI can report without a traceback."""

    def __init__(self, code: ErrorCode, message: str, *, path: Path | None = None) -> None:
        self.code = code
        self.message = message
        self.path = path
        super().__init__(f"[{code.value}] {message}")


class Command(Enum):
    CHECK = "check"
    ADVISE = "advise"
    BASELINE = "baseline"


class ExitCode(IntEnum):
    OK = 0
    FAILED = 1
    USAGE = 2


# ------------------------------------------------------------------ boundary
#
# JSON is the only place raw dictionaries are allowed. Everything below parses
# once, into the models above, and never looks at a raw dict again.


@dataclass(frozen=True, slots=True)
class Baseline:
    """The committed pins that `check` ratchets against."""

    entrypoints: Mapping[NodeId, Budget]
    opam_packages: frozenset[str]
    unreferenced: frozenset[Edge]


def _read_json(path: Path) -> Any | None:
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        raise DepsError(
            ErrorCode.MALFORMED_JSON, f"{path} is not valid JSON: {error}", path=path
        ) from error


def parse_baseline(raw: Any) -> Baseline:
    entrypoints = {
        NodeId(node_id): Budget(libs=int(value["libs"]), opam=int(value["opam"]))
        for node_id, value in raw.get("entrypoints", {}).items()
    }
    unreferenced = {
        (NodeId(pair[0]), NodeId(pair[1])) for pair in raw.get("unreferenced", []) if len(pair) == 2
    }
    return Baseline(
        entrypoints=entrypoints,
        opam_packages=frozenset(raw.get("opam_packages", [])),
        unreferenced=frozenset(unreferenced),
    )


def parse_rules(raw: Any, key: str) -> list[LayeringRule]:
    if raw is None:
        return []
    return [
        LayeringRule(
            from_pattern=rule["from"],
            to_pattern=rule["to"],
            why=rule.get("why", ""),
        )
        for rule in raw.get(key, [])
    ]


def load_baseline() -> Baseline:
    raw = _read_json(BASELINE_PATH)
    if raw is None:
        raise DepsError(
            ErrorCode.BASELINE_MISSING,
            f"{BASELINE_PATH} is missing; {BASELINE_HINT}",
            path=BASELINE_PATH,
        )
    return parse_baseline(raw)


def baseline_document(graph: DuneGraph, sources: SourceIndex) -> dict[str, Any]:
    """The baseline as plain JSON-ready data. The serialization boundary."""
    index = analysis.impact_index(graph)
    unreferenced = sorted(
        [found.source, found.dep]
        for found in analysis.unreferenced_deps(graph, sources)
        if analysis.impact_of(index, (found.source, found.dep)) >= analysis.IMPACT_THRESHOLD
    )
    return {
        "_comment": list(BASELINE_COMMENT),
        "entrypoints": {
            node_id: {"libs": budget.libs, "opam": budget.opam}
            for node_id, budget in analysis.budgets(graph).items()
        },
        "opam_packages": analysis.external_packages(graph),
        "unreferenced": unreferenced,
    }


# --------------------------------------------------------------------- check


def _budget_failures(current: Mapping[NodeId, Budget], baseline: Baseline) -> list[Failure]:
    failures: list[Failure] = []
    for node_id in sorted(set(current) | set(baseline.entrypoints)):
        now = current.get(node_id)
        was = baseline.entrypoints.get(node_id)
        if was is None:
            # `now` cannot be None here: the id came from one of the two maps.
            assert now is not None
            failures.append(NewEntrypoint(entrypoint=node_id, budget=now))
            continue
        if now is None:
            failures.append(MissingEntrypoint(entrypoint=node_id))
            continue
        failures.extend(
            BudgetMoved(entrypoint=node_id, metric=metric, was=was.get(metric), now=now.get(metric))
            for metric in Metric
            if now.get(metric) != was.get(metric)
        )
    return failures


def _opam_failures(current: Iterable[str], baseline: Baseline) -> list[Failure]:
    now = set(current)
    failures: list[Failure] = [
        OpamPackageAdded(package=package) for package in sorted(now - baseline.opam_packages)
    ]
    failures.extend(
        OpamPackageRemoved(package=package) for package in sorted(baseline.opam_packages - now)
    )
    return failures


def _unused_dep_failures(
    unreferenced: Sequence[UnreferencedDep], index: ImpactIndex, baseline: Baseline
) -> list[Failure]:
    failures: list[Failure] = []
    for found in unreferenced:
        edge = (found.source, found.dep)
        reduction = analysis.impact_of(index, edge)
        if reduction < analysis.IMPACT_THRESHOLD or edge in baseline.unreferenced:
            continue
        failures.append(UnusedHeavyDep(source=found.source, dep=found.dep, reduction=reduction))
    return failures


def collect_failures(
    graph: DuneGraph, sources: SourceIndex, baseline: Baseline, forbidden: Sequence[LayeringRule]
) -> list[Failure]:
    """Every way the tree currently disagrees with its pins. Pure."""
    current = analysis.budgets(graph)
    failures = _budget_failures(current, baseline)
    failures.extend(_opam_failures(analysis.external_packages(graph), baseline))
    failures.extend(
        LayeringBroken(violation=violation)
        for violation in analysis.rule_violations(graph, forbidden)
    )
    failures.extend(
        _unused_dep_failures(
            analysis.unreferenced_deps(graph, sources), analysis.impact_index(graph), baseline
        )
    )
    return failures


def run_check(graph: DuneGraph, sources: SourceIndex) -> ExitCode:
    baseline = load_baseline()
    forbidden = parse_rules(_read_json(RULES_PATH), "forbidden")
    failures = collect_failures(graph, sources, baseline, forbidden)

    if failures:
        print(f"Dependency check failed ({len(failures)} problem(s)):\n")
        for failure in failures:
            print(f"  * {render_failure(graph, failure)}\n")
        print("Run `make deps-advice` for the full picture of what can be removed.")
        return ExitCode.FAILED

    print(
        f"Dependency check passed: {len(analysis.budgets(graph))} executables within budget, "
        f"{len(analysis.external_packages(graph))} opam packages, "
        f"{len(forbidden)} layering rule(s) held."
    )
    return ExitCode.OK


# -------------------------------------------------------------------- advise


def _section(title: str) -> None:
    print(f"\n{title}")
    print("-" * len(title))


def run_advise(graph: DuneGraph, sources: SourceIndex) -> ExitCode:
    index = analysis.impact_index(graph)
    pending = parse_rules(_read_json(RULES_PATH), "pending")

    print(f"Dependency advice for {graph.root}")
    edge_count = sum(len(deps) for deps in graph.edges.values())
    print(
        f"{len(graph.nodes)} stanzas, {edge_count} internal edges, "
        f"{len(analysis.external_packages(graph))} opam packages"
    )

    weighted: list[tuple[int, UnreferencedDep, NodeId]] = []
    free: list[UnreferencedDep] = []
    for found in analysis.unreferenced_deps(graph, sources):
        impact = index.get((found.source, found.dep))
        if impact is None:
            free.append(found)
        else:
            weighted.append((impact.reduction, found, impact.target))
    weighted.sort(key=lambda row: -row[0])

    _section("1. Declared, never referenced, and expensive -- delete these first")
    if not weighted:
        print("  none")
    for reduction, found, target in weighted:
        source = graph.nodes[found.source]
        print(
            f"  {source.name:<38} drop {graph.nodes[found.dep].name:<32}  "
            f"-{reduction} libs for {graph.nodes[target].name}"
        )
        print(f"      edit {source.directory}/dune")

    _section("2. Referenced for almost nothing, but very heavy -- worth a refactor")
    thin = analysis.thin_deps(graph, sources, index)
    if not thin:
        print("  none")
    for found in thin:
        dep_node = graph.nodes[found.dep]
        symbols = sources.used_symbols(graph.nodes[found.source], dep_node.module_name)
        shown = ", ".join(symbols[:ADVICE_SAMPLE_SYMBOLS]) or "(no qualified uses; likely `open`)"
        print(
            f"  {graph.nodes[found.source].name:<38} -> {dep_node.name:<30}  "
            f"-{found.reduction} libs for {graph.nodes[found.target].name}"
        )
        print(f"      {found.references} reference(s), uses: {shown}")

    _section("3. Declared, never referenced, but no weight -- hygiene only")
    by_stanza: defaultdict[NodeId, list[NodeId]] = defaultdict(list)
    for found in free:
        by_stanza[found.source].append(found.dep)
    print(f"  {len(free)} dependencies across {len(by_stanza)} stanzas")
    worst = sorted(by_stanza.items(), key=lambda item: -len(item[1]))[:ADVICE_TOP_STANZAS]
    for node_id, deps in worst:
        sample = ", ".join(graph.nodes[dep].name for dep in sorted(deps)[:ADVICE_SAMPLE_DEPS])
        print(f"  {graph.nodes[node_id].directory:<46} {len(deps):2d} unused: {sample}")

    _section("4. Layering rules we want but do not hold yet")
    violations = analysis.rule_violations(graph, pending)
    if not violations:
        print("  none")
    for violation in violations:
        print(f"  {violation.rule.from_pattern} must not reach {violation.rule.to_pattern}")
        print(f"      {violation.rule.why}")
        print(f"      {analysis.format_path(graph, violation.path)}")

    _section("5. Heaviest entrypoints")
    rows = sorted(
        (
            (len(graph.closure(node_id)), len(graph.external_closure(node_id)), node_id)
            for node_id in analysis.shipped_entrypoints(graph)
        ),
        reverse=True,
    )
    for libs, opam, node_id in rows[:ADVICE_TOP_ENTRYPOINTS]:
        print(f"  {libs:4d} libs  {opam:3d} opam  {graph.nodes[node_id].name}")

    print(
        "\nEverything above is a heuristic over source text. "
        "Confirm each removal with `dune build @check`."
    )
    return ExitCode.OK


# ------------------------------------------------------------------ baseline


def run_baseline(graph: DuneGraph, sources: SourceIndex) -> ExitCode:
    document = json.dumps(baseline_document(graph, sources), indent=2, sort_keys=True)
    BASELINE_PATH.write_text(f"{document}\n", encoding="utf-8")
    print(f"wrote {BASELINE_PATH}")
    return ExitCode.OK


# ----------------------------------------------------------------------- cli


def _parse_args(argv: Sequence[str] | None) -> tuple[Command, Path]:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("command", choices=[command.value for command in Command])
    parser.add_argument("--root", default="src", help="source tree to scan (default: src)")
    args = parser.parse_args(argv)
    return Command(args.command), Path(args.root)


def run(command: Command, root: Path) -> ExitCode:
    if not root.is_dir():
        raise DepsError(
            ErrorCode.ROOT_NOT_A_DIRECTORY,
            f"no such directory: {root} (run from the repository root)",
            path=root,
        )
    graph = load_graph(root)
    sources = SourceIndex(root)
    match command:
        case Command.CHECK:
            return run_check(graph, sources)
        case Command.ADVISE:
            return run_advise(graph, sources)
        case Command.BASELINE:
            return run_baseline(graph, sources)
        case _ as unreachable:
            assert_never(unreachable)


def main(argv: Sequence[str] | None = None) -> int:
    command, root = _parse_args(argv)
    try:
        return int(run(command, root))
    except DepsError as error:
        print(f"error: {error.message}", file=sys.stderr)
        return int(
            ExitCode.USAGE if error.code is ErrorCode.ROOT_NOT_A_DIRECTORY else ExitCode.FAILED
        )


def _entrypoint() -> NoReturn:
    sys.exit(main())


if __name__ == "__main__":
    _entrypoint()
