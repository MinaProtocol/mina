#!/usr/bin/env python3
"""Dependency gate and advisor for the OCaml tree.

    python3 maintenance/deps/main.py check     # CI gate, fails on regression
    python3 maintenance/deps/main.py advise    # human report: what to delete
    python3 maintenance/deps/main.py baseline  # re-pin baseline.json

Runs without dune, without a switch and without any opam package: it reads
`dune` files directly. See maintenance/README.md for what that costs us.
"""

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import analysis  # noqa: E402
from graph import DuneGraph  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
BASELINE_PATH = os.path.join(HERE, "baseline.json")
RULES_PATH = os.path.join(HERE, "rules.json")

BASELINE_HINT = "run `make deps-baseline` and commit maintenance/deps/baseline.json"


def load_json(path, default):
    if not os.path.exists(path):
        return default
    with open(path, encoding="utf-8") as handle:
        return json.load(handle)


def build_baseline(graph):
    index = analysis.impact_index(graph)
    unreferenced = []
    for nid, dep in analysis.unreferenced_deps(graph):
        reduction = index.get((nid, dep), (0, None))[0]
        if reduction >= analysis.IMPACT_THRESHOLD:
            unreferenced.append([nid, dep])
    return {
        "_comment": [
            "Generated by `make deps-baseline`; do not hand-edit.",
            "entrypoints: transitive internal libraries and opam packages per executable.",
            "unreferenced: declared deps with no module reference AND real closure weight.",
            "Numbers may only be changed together with the dune change that causes them.",
        ],
        "entrypoints": analysis.budget(graph),
        "opam_packages": analysis.external_packages(graph),
        "unreferenced": sorted(unreferenced),
    }


# --------------------------------------------------------------------- check


def check(graph):
    baseline = load_json(BASELINE_PATH, None)
    if baseline is None:
        print("error: %s is missing; %s" % (BASELINE_PATH, BASELINE_HINT))
        return 1

    failures = []
    current = analysis.budget(graph)
    expected = baseline.get("entrypoints", {})

    for nid in sorted(set(current) | set(expected)):
        now = current.get(nid)
        was = expected.get(nid)
        if was is None:
            failures.append(
                "new executable %s (%d libs, %d opam packages) is not in the baseline\n"
                "    -> %s" % (nid, now["libs"], now["opam"], BASELINE_HINT)
            )
            continue
        if now is None:
            failures.append("executable %s disappeared from the tree\n    -> %s" % (nid, BASELINE_HINT))
            continue
        for key, label in (("libs", "internal libraries"), ("opam", "opam packages")):
            if now[key] > was[key]:
                failures.append(
                    "%s gained %d %s (%d -> %d)\n"
                    "    -> a dune change made this executable heavier; drop the dependency,\n"
                    "       or if it is intended, %s"
                    % (nid, now[key] - was[key], label, was[key], now[key], BASELINE_HINT)
                )
            elif now[key] < was[key]:
                failures.append(
                    "%s lost %d %s (%d -> %d) -- nice, but the baseline must record it\n"
                    "    -> %s" % (nid, was[key] - now[key], label, was[key], now[key], BASELINE_HINT)
                )

    current_opam = set(analysis.external_packages(graph))
    expected_opam = set(baseline.get("opam_packages", []))
    for added in sorted(current_opam - expected_opam):
        failures.append(
            "new opam dependency introduced: %s\n"
            "    -> new third-party packages need a look from CODEOWNERS; once agreed, %s"
            % (added, BASELINE_HINT)
        )
    for removed in sorted(expected_opam - current_opam):
        failures.append("opam dependency %s is no longer used\n    -> %s" % (removed, BASELINE_HINT))

    rules = load_json(RULES_PATH, {})
    for rule, nid, reached, path in analysis.rule_violations(graph, rules.get("forbidden", [])):
        failures.append(
            "layering rule broken: %s must not reach %s\n"
            "    %s\n"
            "    via %s"
            % (rule["from"], rule["to"], rule.get("why", ""), analysis.format_path(graph, path))
        )

    index = analysis.impact_index(graph)
    known = {tuple(pair) for pair in baseline.get("unreferenced", [])}
    for nid, dep in analysis.unreferenced_deps(graph):
        edge = (nid, dep)
        reduction = index.get(edge, (0, None))[0]
        if reduction < analysis.IMPACT_THRESHOLD or edge in known:
            continue
        failures.append(
            "%s declares %s but never references %s, and it costs %d libraries\n"
            "    -> delete it from %s/dune, or if it is linked for side effects, %s"
            % (
                graph.nodes[nid].name,
                graph.nodes[dep].name,
                graph.nodes[dep].module_name,
                reduction,
                graph.nodes[nid].directory,
                BASELINE_HINT,
            )
        )

    if failures:
        print("Dependency check failed (%d problem(s)):\n" % len(failures))
        for failure in failures:
            print("  * %s\n" % failure)
        print("Run `make deps-advice` for the full picture of what can be removed.")
        return 1

    print(
        "Dependency check passed: %d executables within budget, %d opam packages, "
        "%d layering rule(s) held."
        % (len(current), len(current_opam), len(rules.get("forbidden", [])))
    )
    return 0


# -------------------------------------------------------------------- advise


def section(title):
    print("\n" + title)
    print("-" * len(title))


def advise(graph):
    index = analysis.impact_index(graph)
    rules = load_json(RULES_PATH, {})

    print("Dependency advice for %s" % graph.root)
    print("%d stanzas, %d internal edges, %d opam packages"
          % (len(graph.nodes), sum(len(v) for v in graph.edges.values()),
             len(analysis.external_packages(graph))))

    unreferenced = analysis.unreferenced_deps(graph)
    weighted = []
    free = []
    for nid, dep in unreferenced:
        reduction, target = index.get((nid, dep), (0, None))
        (weighted if reduction > 0 else free).append((reduction, nid, dep, target))
    weighted.sort(key=lambda row: -row[0])

    section("1. Declared, never referenced, and expensive -- delete these first")
    if not weighted:
        print("  none")
    for reduction, nid, dep, target in weighted:
        print("  %-38s drop %-32s  -%d libs for %s"
              % (graph.nodes[nid].name, graph.nodes[dep].name, reduction,
                 graph.nodes[target].name))
        print("      edit %s/dune" % graph.nodes[nid].directory)

    section("2. Referenced for almost nothing, but very heavy -- worth a refactor")
    thin = analysis.thin_deps(graph, index)
    if not thin:
        print("  none")
    for reduction, count, source, dep, target in thin:
        symbols = analysis.used_symbols(graph, source, dep)
        shown = ", ".join(symbols[:6]) or "(no qualified uses; likely `open`)"
        print("  %-38s -> %-30s  -%d libs for %s"
              % (graph.nodes[source].name, graph.nodes[dep].name, reduction,
                 graph.nodes[target].name))
        print("      %d reference(s), uses: %s" % (count, shown))

    section("3. Declared, never referenced, but no weight -- hygiene only")
    by_stanza = {}
    for _, nid, dep, _ in free:
        by_stanza.setdefault(nid, []).append(dep)
    print("  %d dependencies across %d stanzas" % (len(free), len(by_stanza)))
    worst = sorted(by_stanza.items(), key=lambda kv: -len(kv[1]))[:10]
    for nid, deps in worst:
        print("  %-46s %2d unused: %s"
              % (graph.nodes[nid].directory, len(deps),
                 ", ".join(graph.nodes[d].name for d in sorted(deps)[:5])))

    section("4. Layering rules we want but do not hold yet")
    pending = rules.get("pending", [])
    if not pending:
        print("  none")
    for rule, nid, reached, path in analysis.rule_violations(graph, pending):
        print("  %s must not reach %s" % (rule["from"], rule["to"]))
        print("      %s" % rule.get("why", ""))
        print("      %s" % analysis.format_path(graph, path))

    section("5. Heaviest entrypoints")
    rows = sorted(
        ((len(graph.closure(n)), len(graph.external_closure(n)), n)
         for n in analysis.shipped_entrypoints(graph)),
        reverse=True,
    )
    for libs, opam, nid in rows[:20]:
        print("  %4d libs  %3d opam  %s" % (libs, opam, graph.nodes[nid].name))

    print("\nEverything above is a heuristic over source text. "
          "Confirm each removal with `dune build @check`.")
    return 0


# ----------------------------------------------------------------------- cli


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=("check", "advise", "baseline"))
    parser.add_argument("--root", default="src", help="source tree to scan (default: src)")
    args = parser.parse_args(argv)

    if not os.path.isdir(args.root):
        print("error: no such directory: %s (run from the repository root)" % args.root)
        return 2

    graph = DuneGraph(args.root)

    if args.command == "check":
        return check(graph)
    if args.command == "advise":
        return advise(graph)

    with open(BASELINE_PATH, "w", encoding="utf-8") as handle:
        json.dump(build_baseline(graph), handle, indent=2, sort_keys=True)
        handle.write("\n")
    print("wrote %s" % BASELINE_PATH)
    return 0


if __name__ == "__main__":
    sys.exit(main())
